    pub fn from_key(value: &str) -> Self {
        match value {
            "conversation" | "chat" => Self::Conversation,
            "folder" | "files" => Self::Files,
            "agent" => Self::Agent,
            "settings" => Self::Settings,
            "search" => Self::Search,
            "history" => Self::History,
            "grid" | "workspace" => Self::Grid,
            "inspector" | "panel-right" => Self::PanelRight,
            "plus" => Self::Plus,
            "attach" => Self::Attach,
            "image" => Self::Image,
            "code" => Self::Code,
            "send" => Self::Send,
            "more" => Self::More,
            "chevron" => Self::ChevronDown,
            "branch" => Self::Branch,
            "copy" => Self::Copy,
            "check" => Self::Check,
            "close" => Self::Close,
            _ => Self::Terminal,
        }
    }

