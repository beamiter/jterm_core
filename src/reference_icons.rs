//! Coherent 24-unit line-icon geometry for the four native workspace adapters.
//! Draw paths in a 16–18 logical-pixel box with a 1.5-unit round-cap stroke.
//! These are original simple vector primitives, not font-dependent glyphs.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Icon {
    Terminal,
    Conversation,
    Files,
    Agent,
    Settings,
    Search,
    History,
    Grid,
    PanelRight,
    Plus,
    Attach,
    Image,
    Code,
    Send,
    More,
    ChevronDown,
    Branch,
    Copy,
    Check,
    Close,
}

pub type Point = (f32, f32);
pub type Path = &'static [Point];

